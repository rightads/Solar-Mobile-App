from typing import AsyncGenerator
import pytest_asyncio
from httpx import ASGITransport, AsyncClient
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker, create_async_engine
from sqlalchemy.pool import NullPool

from app.core.config import settings
from app.db.base import Base
from app.db.session import get_db
from app.main import app

# Test engine with NullPool to prevent connection reuse and concurrency race conditions in asyncpg
test_db_url = settings.TEST_DATABASE_URL or settings.DATABASE_URL or "postgresql+asyncpg://postgres:postgres@localhost:5432/solar_test_db"
test_engine = create_async_engine(
    test_db_url,
    echo=False,
    poolclass=NullPool,
)

TestingSessionLocal = async_sessionmaker(
    bind=test_engine,
    class_=AsyncSession,
    expire_on_commit=False,
    autocommit=False,
    autoflush=False,
)


@pytest_asyncio.fixture(scope="session", autouse=True)
async def initialize_test_database():
    """Create all tables once at the start of the test session and drop them at the end."""
    async with test_engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
    yield
    async with test_engine.begin() as conn:
        await conn.run_sync(Base.metadata.drop_all)
    await test_engine.dispose()


@pytest_asyncio.fixture(scope="function")
async def db_session() -> AsyncGenerator[AsyncSession, None]:
    """Provide an isolated database session for each test function."""
    async with TestingSessionLocal() as session:
        yield session
        await session.rollback()


